multiset<int> ms1, ms2;
void balance(){
    int sz = ms1.size() + ms2.size();

    int sz1 = (sz+1)/2;
    int sz2 = sz - sz1;

    while(ms1.size() > sz1){
        ms2.insert(*ms1.rbegin());
        ms1.erase(ms1.find(*ms1.rbegin()));
    }

    while(ms2.size() > sz2){
        ms1.insert(*ms2.begin());
        ms2.erase(ms2.begin());
    }
}
void add(int v){
    if(ms1.empty()){
        ms1.insert(v);
    }
    else{
        int mx = *ms1.rbegin();
        if(v < mx ){
            ms1.insert(v);
        }
        else ms2.insert(v);

    }

    balance();
}

void remove(int v){

    if(ms1.find(v) != ms1.end()){
        ms1.erase(ms1.find(v));
    }
    else ms2.erase(ms2.find(v));

    balance();
}
